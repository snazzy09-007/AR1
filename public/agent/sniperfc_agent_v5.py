    def read_credits(self):
        try:
            element = WebDriverWait(self.driver, 2).until(
                EC.presence_of_element_located(
                    (By.CLASS_NAME, "view-navbar-currency-coins")
                )
            )
            raw = element.text.replace(" ", "").replace(",", "").replace(".", "")
            self.credits = int(raw)
        except Exception:
            pass
        return self.credits

