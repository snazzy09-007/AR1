class SniperFCV5:
    def __init__(self):
        self.engine = dict(DEFAULT_ENGINE)
        self.strategy = dict(DEFAULT_STRATEGY)
        self.driver = None

        self.paused = False
        self.stopped = False
        self.must_refresh = False
        self.must_restart = False
        self.market_ready = False

        self.loops = 0
        self.refresh_count = 0
        self.increment_value = 0
        self.buys = 0
        self.credits = None
        self.next_refresh = 450
        self.last_refresh_at = time.time()
        self.last_heartbeat_at = 0.0
        self.last_quiet_log_at = 0.0
        self.api_online = False
        self._unauth_count = 0
        self.lock = threading.Lock()
        self.http = self.build_session()
        # Anti zombie-stop : un ancien ordre d'arret (status=stopped
        # persistant ou commande stop non consommee) ne doit pas tuer un
        # agent qui vient de demarrer. Grace les STOP_IGNORE_SECONDS
        # premieres secondes, le serveur a le temps de se rearmer.
        self.started_at = time.time()
        self.grace_seconds = 20.0

    def stop_allowed(self):
        return (time.time() - self.started_at) > self.grace_seconds

    # ------------------------------------------------------------------
    # Values and timing
    # ------------------------------------------------------------------
    def engine_int(self, key):
        try:
            return int(self.engine.get(key, DEFAULT_ENGINE.get(key, 0)) or 0)
        except (TypeError, ValueError):
            return int(DEFAULT_ENGINE.get(key, 0) or 0)

    def strategy_int(self, key):
        try:
            return int(self.strategy.get(key, DEFAULT_STRATEGY.get(key, 0)) or 0)
        except (TypeError, ValueError):
            return 0

    def strategy_str(self, key):
        value = self.strategy.get(key, DEFAULT_STRATEGY.get(key, ""))
        return "" if value is None else str(value)

    def strategy_bool(self, key):
        return bool(self.strategy.get(key, DEFAULT_STRATEGY.get(key, False)))

    @staticmethod
    def sleep_between(low, high=None):
        time.sleep(low if high is None else random.uniform(low, high))

    def schedule_refresh(self):
        low = max(10, self.engine_int("refreshMinLoops"))
        high = max(10, self.engine_int("refreshMaxLoops"))
        if low > high:
            low, high = high, low
        self.next_refresh = random.randint(low, high)

